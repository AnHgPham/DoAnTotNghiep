def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--raw-dir", type=Path, default=Path("reports/full_mswc_matrix_analysis/raw"))
    parser.add_argument("--out-dir", type=Path, default=Path("reports/full_mswc_matrix_analysis"))
    args = parser.parse_args()

    args.out_dir.mkdir(parents=True, exist_ok=True)
    log_paths = [
        args.raw_dir / "full_mswc_12_combo_phase1_e5_ep150_manifest20.log",
        args.raw_dir / "full_mswc_12_combo_phase1_e5_ep150_manifest20_resume.log",
    ]
    tsv_paths = [
        args.raw_dir / "full_mswc_12_combo_phase1_e5_ep150_manifest20_runs.tsv",
        args.raw_dir / "full_mswc_edgespot_mfcc_4_combo_phase1_e5_ep150_manifest20_runs.tsv",
    ]
    experiments = parse_logs(log_paths)
    status = load_status(tsv_paths)
    df = build_table(experiments, status)
    if df.empty:
        raise SystemExit("No experiments with GSC-dev metrics were parsed.")
    save_tables(df, args.out_dir)
    save_det_summary_tables(df, args.out_dir)
    effect_df = save_effect_tables(df, args.out_dir)
    save_plots(df, effect_df, args.out_dir)
    write_report(df, effect_df, args.out_dir)
    print(f"Wrote {len(df)} experiment rows to {args.out_dir}")
    print(df.sort_values("acc1_far", ascending=False)[["combo", "best_epoch", "acc1_far", "acc5_far", "frr5_far"]].to_string(index=False))


if __name__ == "__main__":
    main()
