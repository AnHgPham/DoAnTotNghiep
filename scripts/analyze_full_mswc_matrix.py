def effect_delta(effect_df: pd.DataFrame, effect: str, scope: str, col: str = "delta_acc1_pp") -> str:
    if effect_df.empty:
        return "N/A"
    hit = effect_df[(effect_df["effect"] == effect) & (effect_df["scope"] == scope)]
    if hit.empty:
        return "N/A"
    return f"{float(hit.iloc[0][col]):+.2f} pp"


